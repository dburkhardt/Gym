"""Ephemeral collector proof for a receipt-selected fresh attempt, not continuation.

Checkpoint bearer routes authorize checkpoint operations, and MCP signatures authorize
session tools. Neither admits a new /run. This proof travels only over the native
opaque relay; its key is generated by managed CLI before service startup, never config.
"""

import base64
import hashlib
import hmac
import json
import os
import re
import secrets
from pathlib import Path

from nemo_gym.episode_types import EpisodeId


KEY_ENV = "NEMO_GYM_RESTART_ADMISSION_KEY"
HEADER = "x-nemo-gym-restart-admission"


def install_key():
    # Never trust a caller-provided or prior CLI key.
    os.environ[KEY_ENV] = secrets.token_hex(32)


def _encode(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()


def _digest(value):
    return hashlib.sha256(_encode(value)).hexdigest()


def _key():
    key = os.environ.get(KEY_ENV, "")
    if len(key) != 64:
        raise ValueError("Explicit restart lacks managed CLI admission key")
    return bytes.fromhex(key)


def _stores(directories):
    result = []
    for directory in directories:
        root = Path(directory).resolve()
        identity = root / ".capture-store-identity"
        if identity.is_symlink() or not identity.is_file():
            raise ValueError("Explicit restart capture identity missing")
        value = identity.read_text()
        if not re.fullmatch(r"[0-9a-f]{32}", value):
            raise ValueError("Explicit restart capture identity malformed")
        result.append({"path": str(root), "identity": value})
    return sorted(result, key=lambda item: item["path"])


def headers_for_request(admission, request, *, agent):
    from nemo_gym.base_responses_api_model import maybe_rollout_id_from_run_body

    if not admission:
        return {}
    episode = EpisodeId.from_capture_key(maybe_rollout_id_from_run_body(request))
    prior = admission["prior"].get(episode.rollout_id)
    if prior is None:
        return {}
    return {
        HEADER: sign(
            request,
            agent=agent,
            prior=prior,
            binding=admission["binding"],
            receipt_sha256=admission["receipt_sha256"],
            capture_dirs=admission["capture_dirs"],
        )
    }


def sign(request, *, agent, prior, binding, receipt_sha256, capture_dirs):
    from nemo_gym.base_responses_api_model import maybe_rollout_id_from_run_body

    if not all(isinstance(x, str) and re.fullmatch(r"[0-9a-f]{64}", x) for x in (binding, receipt_sha256)):
        raise ValueError("Explicit restart requires source and receipt digests")
    current = maybe_rollout_id_from_run_body(request)
    before, after = EpisodeId.from_capture_key(prior), EpisodeId.from_capture_key(current)
    if before.rollout_id != after.rollout_id or after.attempt <= before.attempt:
        raise ValueError("Explicit restart admission identity mismatch")
    payload = dict(
        version=1,
        nonce=secrets.token_hex(32),
        request_sha256=_digest(request),
        agent=agent,
        prior=prior,
        current=current,
        binding=binding,
        receipt_sha256=receipt_sha256,
        capture_dirs=_stores(capture_dirs),
    )
    encoded = _encode(payload)
    return base64.urlsafe_b64encode(encoded).decode() + "." + hmac.new(_key(), encoded, hashlib.sha256).hexdigest()


def consume(proof, request, *, agent, config, consumed):
    """Validate and atomically consume without awaiting, before any scientific work."""
    from nemo_gym.base_responses_api_model import (
        assert_guarded_rollout_dispatch_safe,
        maybe_rollout_id_from_run_body,
        model_call_capture_dirs_from_config,
    )

    if not isinstance(proof, str) or len(proof) > 16384:
        raise ValueError("Missing explicit restart admission")
    try:
        encoded, signature = proof.split(".")
        raw = base64.b64decode(encoded, altchars=b"-_", validate=True)
        if not hmac.compare_digest(signature, hmac.new(_key(), raw, hashlib.sha256).hexdigest()):
            raise ValueError("Invalid explicit restart signature")
        payload = json.loads(raw)
    except (TypeError, KeyError, json.JSONDecodeError) as error:
        raise ValueError("Malformed explicit restart admission") from error
    required = {
        "version",
        "nonce",
        "request_sha256",
        "agent",
        "prior",
        "current",
        "binding",
        "receipt_sha256",
        "capture_dirs",
    }
    if (
        not isinstance(payload, dict)
        or set(payload) != required
        or not all(
            isinstance(payload[x], str) and re.fullmatch(r"[0-9a-f]{64}", payload[x])
            for x in ("nonce", "request_sha256", "binding", "receipt_sha256")
        )
    ):
        raise ValueError("Malformed explicit restart proof fields")
    target = config.get(agent, {}).get("responses_api_agents", {}).get("scicode_agent", {})
    if not target or (
        target.get("num_workers") is not None
        and (type(target["num_workers"]) is not int or target["num_workers"] != 1)
    ):
        raise ValueError("Explicit SciCode restart requires one native agent worker")
    current = maybe_rollout_id_from_run_body(request)
    dirs = model_call_capture_dirs_from_config(config)
    if (
        config.get("provider_dispatch_guard") is not True
        or payload.get("version") != 1
        or payload.get("agent") != agent
        or payload.get("current") != current
        or payload.get("request_sha256") != _digest(request)
        or payload.get("capture_dirs") != _stores(dirs)
        or not dirs
    ):
        raise ValueError("Explicit restart request/role/capture binding mismatch")
    before, after = EpisodeId.from_capture_key(payload["prior"]), EpisodeId.from_capture_key(current)
    if before.rollout_id != after.rollout_id or before.attempt >= after.attempt:
        raise ValueError("Explicit restart prior identity mismatch")
    if current in consumed:
        raise ValueError("Explicit restart admission already consumed")
    if any(not Path(p).is_dir() for p in dirs):
        raise ValueError("Explicit restart capture directory missing")
    assert_guarded_rollout_dispatch_safe([request], dirs, admitted_prior_attempts=frozenset([payload["prior"]]))
    consumed.add(current)
    return payload
